-- Initial RideShare database schema.
-- Based on the existing PostgreSQL schema export.

-- 1. Users
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255),
    name VARCHAR(255) NOT NULL,
    phone VARCHAR(255),
    role VARCHAR(255),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT uk_users_phone UNIQUE (phone),
    CONSTRAINT users_role_check
        CHECK (role IN ('RIDER', 'DRIVER'))
);

-- 2. Vehicles
CREATE TABLE vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model VARCHAR(255),
    registration_number VARCHAR(255) NOT NULL,
    vehicle_type VARCHAR(255),
    CONSTRAINT ukf6xfxoc4kprkjkst07tq63y6
        UNIQUE (registration_number),
    CONSTRAINT vehicles_vehicle_type_check
        CHECK (vehicle_type IN ('HATCHBACK', 'SEDAN', 'SUV', 'MUV'))
);

-- 3. Drivers
CREATE TABLE drivers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    license_number VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL,
    user_id BIGINT NOT NULL,
    vehicle_id BIGINT NOT NULL,

    CONSTRAINT uk_drivers_license_number UNIQUE (license_number),
    CONSTRAINT uk_drivers_user_id UNIQUE (user_id),
    CONSTRAINT uk_drivers_vehicle_id UNIQUE (vehicle_id),

    CONSTRAINT drivers_status_check
        CHECK (status IN ('AVAILABLE', 'BUSY', 'OFFLINE')),

    CONSTRAINT fk_drivers_user
        FOREIGN KEY (user_id) REFERENCES users(id),

    CONSTRAINT fk_drivers_vehicle
        FOREIGN KEY (vehicle_id) REFERENCES vehicles(id)
);

-- 4. Rides
CREATE TABLE rides (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dropoff_location VARCHAR(255) NOT NULL,
    pickup_location VARCHAR(255) NOT NULL,
    requested_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    driver_id BIGINT,
    rider_id BIGINT NOT NULL,
    status VARCHAR(255) NOT NULL,

    CONSTRAINT rides_status_check
        CHECK (
            status IN (
                'REQUESTED',
                'ACCEPTED',
                'IN_PROGRESS',
                'COMPLETED',
                'CANCELLED',
                'REJECTED'
            )
        ),

    CONSTRAINT fk_rides_driver
        FOREIGN KEY (driver_id) REFERENCES drivers(id),

    CONSTRAINT fk_rides_rider
        FOREIGN KEY (rider_id) REFERENCES users(id)
);

-- 5. Ride offers
CREATE TABLE ride_offers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    status VARCHAR(20) NOT NULL,
    driver_id BIGINT NOT NULL,
    ride_id BIGINT NOT NULL,

    CONSTRAINT uk_ride_offer_ride_driver
        UNIQUE (ride_id, driver_id),

    CONSTRAINT ride_offers_status_check
        CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'EXPIRED')),

    CONSTRAINT fk_ride_offers_driver
        FOREIGN KEY (driver_id) REFERENCES drivers(id),

    CONSTRAINT fk_ride_offers_ride
        FOREIGN KEY (ride_id) REFERENCES rides(id)
);

-- 6. Ride indexes
CREATE INDEX idx_rides_driver_id ON rides(driver_id);
CREATE INDEX idx_rides_rider_id ON rides(rider_id);
CREATE INDEX idx_rides_status ON rides(status);
