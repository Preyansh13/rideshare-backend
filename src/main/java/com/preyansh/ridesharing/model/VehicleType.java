package com.preyansh.ridesharing.model;

// Enum defining the supported vehicle categories in the ride-sharing system.
public enum VehicleType {

    // Compact vehicle with a rear hatch door.
    HATCHBACK,

    // Passenger car with a separate trunk.
    SEDAN,

    // Sport Utility Vehicle, typically offering more space and ground clearance.
    SUV,

    // Multi Utility Vehicle, generally designed to accommodate more passengers.
    MUV
}